# Question 5: Concept of a Classification Report (Theory Answer)
# What is it? A classification report is a performance evaluation metric text summary that shows the main classification metrics on a per-class basis.

# Why is it used? It is used to measure the quality of predictions from a classification model beyond simple accuracy, giving insights into false positives, false negatives, precision, and recall per class.

# What type of models require it? Supervised machine learning classification models (such as Logistic Regression, Support Vector Machines, Random Forests, Decision Trees, etc.) require it to evaluate categorical output predictions.